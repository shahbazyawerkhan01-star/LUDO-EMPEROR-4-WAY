export function tr(lang: string, key: string, vars?: Record<string, string>): string {
    let s = (T[lang] && T[lang][key]) || en[key] || key;
    if (vars) for (const k of Object.keys(vars)) s = s.split(`{${k}}`).join(vars[k]);
    return s;
}

